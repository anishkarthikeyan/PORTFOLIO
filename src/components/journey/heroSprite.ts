export type HeroFrame = keyof typeof HERO_FRAMES;

export const HERO_FRAME_ORDER = Object.keys(HERO_FRAMES) as HeroFrame[];

/** Index of each frame in the horizontal sprite sheet. */
export const HERO_FRAME_INDEX = Object.fromEntries(HERO_FRAME_ORDER.map((n, i) => [n, i])) as Record<HeroFrame, number>;

/**
 * One SVG sprite sheet (all frames side by side) as a data URI, so the
 * character is a single element whose frame changes via background-position.
 */
export function buildHeroSheet(): string {
  let rects = "";
  HERO_FRAME_ORDER.forEach((name, i) => {
    const ox = i * HERO_W;
    HERO_FRAMES[name].forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        const ch = row[x];
        let end = x + 1;
        while (end < row.length && row[end] === ch) end++;
        const fill = HERO_PALETTE[ch];
        if (ch !== "." && fill) rects += `<rect x="${ox + x}" y="${y}" width="${end - x}" height="1" fill="${fill}"/>`;
        x = end;
      }
    });
  });
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${HERO_W * HERO_FRAME_ORDER.length} ${HERO_H}" shape-rendering="crispEdges">${rects}</svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
}
